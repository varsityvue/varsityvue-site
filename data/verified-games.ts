export function applyVerifiedGames(baseGames: Game[]): Game[] {
  const existingIds = new Set(baseGames.map((game) => game.id));

  const updatedGames = baseGames.map((game) => ({
    ...game,
    ...(verifiedResultOverrides[game.id] ?? {}),
  }));

  return [
    ...updatedGames,
    ...verifiedGameAdditions.filter((game) => !existingIds.has(game.id)),
  ];
}
