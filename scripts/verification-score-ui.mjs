import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
const origin = 'http://127.0.0.1:3000';
const game = 'jacksboro-at-cisco-2026-week-5';
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
async function schoolPulse(slug) {
 const inspection=await browser.newPage();
 await inspection.goto(origin+'/schools/'+slug,{waitUntil:'domcontentloaded'});
 const record=await inspection.getByText('Season Overview',{exact:true}).locator('..').locator('p').nth(1).innerText();
 const lastFive=await inspection.getByText('Last 5',{exact:true}).locator('..').locator('span').allInnerTexts();
 await inspection.close();
 return {record,lastFive};
}
const ciscoBefore=await schoolPulse('cisco');
const jacksboroBefore=await schoolPulse('jacksboro');
await page.goto(origin + '/verification-login', { waitUntil: 'networkidle' });
await page.getByText('Correcting a finalized result',{exact:true}).waitFor();
assert.equal(await page.locator('[name=away_score]').inputValue(),'28');
assert.equal(await page.locator('[name=home_score]').inputValue(),'21');
assert.match(await page.locator('main').innerText(), /You are correcting a finalized result/);
assert.equal(await page.locator('[name=reason]').getAttribute('required'),'');
await page.locator('[name=away_score]').fill('27');
await page.locator('[name=home_score]').fill('28');
await page.locator('[name=reason]').fill('Official scorebook correction');
await page.getByRole('button',{name:'Review correction'}).click();
await page.getByText('Confirm final result correction').waitFor({ timeout: 10000 });
assert.match(await page.locator('form').innerText(),/Before: Jacksboro 28 · Cisco 21/);
assert.match(await page.locator('form').innerText(),/After: Jacksboro 27 · Cisco 28/);
for (const width of [390,400,430]) {
 await page.setViewportSize({width,height:844});
 const dimensions=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,inner:window.innerWidth}));
 assert.ok(dimensions.scroll<=dimensions.inner,`overflow at ${width}: ${JSON.stringify(dimensions)}`);
 await page.getByRole('button',{name:'Save confirmed correction'}).scrollIntoViewIfNeeded();
 assert.ok(await page.getByRole('button',{name:'Save confirmed correction'}).isVisible());
}
await page.getByRole('button',{name:'Save confirmed correction'}).click();
await page.getByRole('status').getByText(/Correction saved/).waitFor({timeout:15000});
assert.equal(await page.locator('[name=away_score]').inputValue(),'27');
assert.equal(await page.locator('[name=home_score]').inputValue(),'28');
console.log('authenticated final correction, review, save, 390/400/430 widths: PASS');
await page.goto(origin+'/games/'+game,{waitUntil:'domcontentloaded'});
const centerText=await page.locator('main').innerText();
assert.match(centerText,/Jacksboro/);
assert.match(centerText,/Cisco/);
assert.match(centerText,/\b27\b/);
assert.match(centerText,/\b28\b/);
await page.goto(origin+'/scoreboard',{waitUntil:'domcontentloaded'});
const scoreboardLinks=await page.locator(`a[href*="/games/${game}"]`).allInnerTexts();
assert.ok(scoreboardLinks.some(t=>/\b27\b/.test(t)&&/\b28\b/.test(t)),`scoreboard card: ${JSON.stringify(scoreboardLinks)}`);
const ciscoAfter=await schoolPulse('cisco');
const jacksboroAfter=await schoolPulse('jacksboro');
assert.notEqual(ciscoBefore.record,ciscoAfter.record,'Cisco season record stayed stale');
assert.notEqual(jacksboroBefore.record,jacksboroAfter.record,'Jacksboro season record stayed stale');
assert.equal(ciscoAfter.lastFive.at(-1),'W');
assert.equal(jacksboroAfter.lastFive.at(-1),'L');
await page.goto(origin+'/pickem',{waitUntil:'domcontentloaded'});
const weekly=await page.getByRole('heading',{name:'Week 5 standings'}).locator('..').innerText();
assert.ok(weekly.indexOf('UI challenger')<weekly.indexOf('Score UI admin'),`weekly standings: ${weekly}`);
await page.goto(origin+'/',{waitUntil:'domcontentloaded'});
const ticker=await page.locator(`section[aria-label*="Scores"] a[href*="/games/${game}"]`).allInnerTexts();
if(ticker.length) assert.ok(ticker.some(t=>/\b27\b/.test(t)&&/\b28\b/.test(t)),`ticker: ${JSON.stringify(ticker)}`);
console.log('rendered Game Center, scoreboard, School Hub Last 5/record, Pick Em weekly ranks: PASS; ticker game displayed:',ticker.length>0);
await page.goto(origin+'/internal/score-review/correct?game='+game);
const stale = await browser.newPage({viewport:{width:400,height:844}});
await stale.goto(origin+'/verification-login',{waitUntil:'networkidle'});
await stale.getByText('Correcting a finalized result',{exact:true}).waitFor();
await page.locator('[name=home_score]').fill('29');
await page.locator('[name=reason]').fill('Second official correction');
await page.getByRole('button',{name:'Review correction'}).click();
await page.getByRole('button',{name:'Save confirmed correction'}).click();
await page.getByRole('status').getByText(/Correction saved/).waitFor({timeout:15000});
await stale.locator('[name=away_score]').fill('30');
await stale.locator('[name=reason]').fill('Stale official correction');
await stale.getByRole('button',{name:'Review correction'}).click();
await stale.getByRole('button',{name:'Save confirmed correction'}).click();
await stale.getByRole('alert').getByText(/game changed|Refresh and review/i).waitFor({timeout:15000});
assert.equal(await stale.locator('[name=home_score]').inputValue(),'29');
assert.equal(await stale.locator('[name=away_score]').inputValue(),'27');
for(const width of [390,400,430]) {
 await stale.setViewportSize({width,height:844});
 assert.ok(await stale.getByRole('alert').filter({hasText:/game changed|Refresh and review/i}).first().isVisible());
 assert.ok(await stale.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
}
console.log('stale UI rejected and refreshed latest revision: PASS');
await page.goto(origin+'/internal/score-review/correct?game=de-leon-at-goldthwaite-2026-week-4');
await page.getByText('Correcting an entered live score').waitFor();
assert.equal(await page.locator('[name=away_score]').inputValue(),'3');
await page.locator('[name=away_score]').fill('10');
await page.locator('[name=period]').fill('Q3');
await page.locator('[name=reason]').fill('Press box verified');
await page.getByRole('button',{name:'Review correction'}).click();
await page.getByRole('button',{name:'Save confirmed correction'}).click();
await page.getByRole('status').getByText(/Correction saved/).waitFor({timeout:15000});
assert.equal(await page.locator('[name=away_score]').inputValue(),'10');
console.log('authenticated live correction: PASS');
assert.deepEqual(errors,[]);
await browser.close();
